#!/usr/bin/env node
// Regenerate docs/trade-rerecord-manifest.md — the worklist of audio slots
// whose dialogue changed and need (re-)recording. Reads every case in
// cases/index.js, pulls each `// re-record: <slot>` marker, stitches the
// adjacent spoken text, and groups by case → character with voice config.
//
// Run after editing any case or generating a new one:
//   node scripts/gen-rerecord-manifest.mjs

import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CASES_DIR = path.join(ROOT, "src/components/game/cases");
const CHAR_TO_STATION = { monk: "monk", demon: "demon", trinity: "marisol", unicorn: "eugene", eugene: "eugene" };

// Read the ordered case id list from cases/index.js (the CASE_FILES import lines).
function caseIds() {
  const idx = fs.readFileSync(path.join(CASES_DIR, "index.js"), "utf8");
  return [...idx.matchAll(/from\s+["']\.\/(case-\d+)["']/g)].map((m) => m[1]);
}

function extract(file) {
  const lines = fs.readFileSync(path.join(CASES_DIR, `${file}.js`), "utf8").split("\n");
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/re-record:\s*([A-Za-z0-9_]+)/);
    if (!m) continue;
    let start = -1;
    for (let j = i; j >= Math.max(0, i - 25); j--) { if (/(^|\s)text:/.test(lines[j])) { start = j; break; } }
    let parts = [];
    if (start !== -1) for (let j = start; j <= i; j++) { const re = /"([^"]*)"/g; let q; while ((q = re.exec(lines[j])) !== null) parts.push(q[1]); }
    out.push({ slot: m[1], text: start === -1 ? "(text not found)" : parts.join("") });
  }
  return out;
}

async function main() {
  let md = `# Terminal Traders — Re-record Manifest\n\nAuto-generated by scripts/gen-rerecord-manifest.mjs. Audio slots whose dialogue\nchanged and need recordings (slots not listed are unchanged). Eugene's lines\nare included for her new vocal — she was previously text-only, so her audio\nplayback wiring is still a separate step.\n`;

  // Eugene has no `// re-record:` markers (text-only in the case files), so pull
  // her lines from the parsed case and synthesize slot names.
  const eugeneItems = (c) => {
    const e = c.stations.eugene; if (!e) return [];
    const num = (String(c.id).match(/(\d+)/) || ["", "000"])[1];
    const slot = (key) => `case${num}_eugene_${key}`.slice(0, 25);
    const out = [];
    const push = (key, t) => { const text = typeof t === "string" ? t : t?.text; if (text) out.push({ slot: slot(key), text }); };
    push("intro", e.intro);
    (e.returnLines || []).forEach((r, i) => push(`return_${i + 1}`, r));
    (e.questions || []).forEach((q, i) => push(`q${i + 1}`, q.a));
    ["believe", "abstain", "doubt"].forEach((k) => push(`react_${k}`, e.verdictReaction?.[k]));
    ["aligned", "missed", "abstained"].forEach((k) => push(`vind_${k}`, e.vindication?.[k]));
    return out;
  };

  let grand = 0;
  for (const file of caseIds()) {
    const c = (await import(pathToFileURL(path.join(CASES_DIR, `${file}.js`)).href)).default;
    const v = {}; for (const [k, st] of Object.entries(c.stations)) v[k] = { character: st.character, voice: JSON.stringify(st.voice ?? null) };
    const items = [...extract(file), ...eugeneItems(c)]; grand += items.length;
    md += `\n## ${file} — ${c.projectName} (${c.ticker}) · ${c.correctVerdict.toUpperCase()} · ${items.length} slots\n`;
    const groups = {};
    for (const it of items) { const cm = it.slot.match(/^case\d+_([a-z0-9]+)/i); (groups[cm ? cm[1].toLowerCase() : "misc"] ||= []).push(it); }
    for (const [tok, list] of Object.entries(groups)) {
      const station = CHAR_TO_STATION[tok] || tok; const info = v[station];
      md += `\n### ${info ? info.character : tok}  *(station: ${station}, voice: ${info ? info.voice : "?"})*\n\n| Slot | Line |\n|---|---|\n`;
      for (const it of list) md += `| \`${it.slot}\` | ${it.text.replace(/\|/g, "\\|").replace(/\n/g, " ")} |\n`;
    }
  }
  md += `\n---\nTotal slots to re-record: **${grand}**\n`;
  fs.writeFileSync(path.join(ROOT, "docs/trade-rerecord-manifest.md"), md);
  console.log(`Wrote docs/trade-rerecord-manifest.md — ${grand} slots`);
}
main().catch((e) => { console.error(e); process.exit(1); });
